const { chromium } = require('playwright-core');
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const ok=(n,c,x)=>console.log((c?'PASS ':'FAIL ')+n+(x!==undefined?' '+JSON.stringify(x):''));
(async()=>{
  const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome'});
  const pg=await (await b.newContext({viewport:{width:393,height:852},serviceWorkers:'block',hasTouch:true,isMobile:true})).newPage(); await pg.addInitScript(()=>{window.__toozKeepSample=true});
  const errs=[]; pg.on('pageerror',e=>errs.push(e.message));
  await pg.goto('http://localhost:8750/'); await sleep(1500);
  await pg.evaluate(()=>{ closeSheet(); const d=LIB.find(x=>x.kind==='sample'); d.bookmarks=[{i:10,name:'First',at:1},{i:50,name:'Second',at:2}]; touch(d); NOTESEG='bm'; showView('notes'); renderNotes(); });
  await sleep(1200);
  const swipe=async(sel,dx)=>pg.evaluate(([sel,dx])=>{ const el=document.querySelector(sel); const r=el.getBoundingClientRect(); const y=r.top+r.height/2, x=r.right-30;
    const T=(cx)=>new Touch({identifier:1,target:el,clientX:cx,clientY:y});
    el.dispatchEvent(new TouchEvent('touchstart',{bubbles:true,cancelable:true,touches:[T(x)]}));
    for(let k=1;k<=6;k++) el.dispatchEvent(new TouchEvent('touchmove',{bubbles:true,cancelable:true,touches:[T(x+dx*k/6)]}));
    el.dispatchEvent(new TouchEvent('touchend',{bubbles:true,cancelable:true,touches:[]})); },[sel,dx]);
  ok('bookmarks listed', await pg.evaluate(()=>document.querySelectorAll('#notesBm .swrow').length===2));
  await swipe('#notesBm .swrow .swfront',-140); await sleep(400);
  ok('swipe left reveals Delete', await pg.evaluate(()=>document.querySelector('#notesBm .swrow').classList.contains('open')));
  await sleep(500);
  await pg.evaluate(()=>document.querySelector('#notesBm .swrow.open .swdel').click()); await sleep(500);
  const r=await pg.evaluate(()=>({n:document.querySelectorAll('#notesBm .swrow').length, left:LIB.find(x=>x.kind==='sample').bookmarks.map(b=>b.name), toast:$('#toastMsg').textContent}));
  ok('delete removes the bookmark', r.n===1 && JSON.stringify(r.left)==='["Second"]' && /deleted/.test(r.toast), r);
  await pg.evaluate(()=>$('#toastAct').click()); await sleep(400);
  ok('undo brings it back', await pg.evaluate(()=>LIB.find(x=>x.kind==='sample').bookmarks.length===2 && document.querySelectorAll('#notesBm .swrow').length===2));
  await swipe('#notesBm .swrow .swfront',-30); await sleep(300);
  ok('short swipe snaps back', await pg.evaluate(()=>!document.querySelector('#notesBm .swrow').classList.contains('open')));
  await sleep(500);
  await pg.evaluate(()=>document.querySelector('#notesBm .swrow [data-nb]').click()); await sleep(1200);
  ok('tapping a bookmark still opens it', await pg.evaluate(()=>R.meta && R.meta.kind==='sample' && !$('#v-reader').hidden));
  ok('no page errors', !errs.length, errs); await b.close();
})();
