const { chromium } = require('playwright-core');
const S='/tmp/claude-0/-home-claude/99ef2298-0981-5d84-8afa-8770d83afcea/scratchpad/';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const ok=(n,c,x)=>console.log((c?'PASS ':'FAIL ')+n+(x!==undefined?' '+JSON.stringify(x):''));
const fs=require('fs');
(async()=>{
  const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args:['--autoplay-policy=no-user-gesture-required']});
  const ctx=await b.newContext({viewport:{width:393,height:852}, serviceWorkers:'block'});
  await ctx.addInitScript(()=>{ window.__toozKeepSample=true; });
  const cors={'access-control-allow-origin':'*'};
  await ctx.route(/cdn\.jsdelivr\.net\/npm\/onnxruntime-web@1\.31\.1\/dist\/(.*)/, r=>{ const f=r.request().url().split('/').pop(); r.fulfill({path:S+'st/ci/latest/node_modules/onnxruntime-web/dist/'+f, headers:Object.assign({'content-type':f.endsWith('.wasm')?'application/wasm':'application/javascript'},cors)}); });
  const pg=await ctx.newPage(); const errs=[]; pg.on('pageerror',e=>errs.push(e.message));
  await pg.goto('http://localhost:8750/'); await sleep(1500);
  /* pretend the old garbled copy was downloaded */
  await pg.evaluate(async()=>{ closeSheet(); const root=await navigator.storage.getDirectory(); const d=await root.getDirectoryHandle('supertonic',{create:true}); await d.getFileHandle('x',{create:true}); S.pipVoice='st-F1'; saveSettings(); });
  const prog=[]; await pg.exposeFunction('__prog',x=>prog.push(x));
  const t0=Date.now();
  const r=await pg.evaluate(async()=>{ await natLoad(p=>window.__prog(p)); const g=await natGen('This is how your books will sound when Tooz reads them aloud, from Isaiah chapter 26 verse 8.'); const buf=await (await fetch(g.url)).arrayBuffer(); return {dur:g.dur, ms:g.ms, b:Array.from(new Uint8Array(buf))}; });
  fs.writeFileSync(S+'st/page_F1.wav', Buffer.from(r.b));
  ok('real model loads in the browser and speaks', r.dur>3, {dur:r.dur, ms:r.ms, total:Date.now()-t0});
  const last=prog[prog.length-1]||{};
  ok('progress counts the whole download', last.pct===100 && last.t>100e6 && prog.every(p=>p.a<=p.t) && prog.length>20, [prog.length, prog[0], last]);
  ok('old copy removed, new folder used', await pg.evaluate(async()=>{ const root=await navigator.storage.getDirectory(); const names=[]; for await (const [n] of root.entries()) names.push(n); return !names.includes('supertonic') && names.includes('supertonic-w8'); }));
  const served=[]; pg.on('request',q=>{ if(/voices\/supertonic/.test(q.url())) served.push(q.url().replace(/^.*supertonic\//,'')); });
  await pg.evaluate(async()=>{ S.pipVoice='st-M2'; saveSettings(); await natLoad(()=>{}); });
  ok('second voice downloads only its small file', served.length===1 && /M2\.json/.test(served[0]), served);
  await pg.evaluate(async()=>{ await openDoc(LIB.find(x=>x.kind==='sample').id); }); await sleep(800);
  await pg.evaluate(()=>{ closeSheet(); $('#rTts').click(); $('#ttsPlay').click(); }); await sleep(12000);
  ok('reads the book aloud', await pg.evaluate(()=>TTS.on && TTS.cur>0), await pg.evaluate(()=>[TTS.on,TTS.cur]));
  await pg.evaluate(()=>$('#rTts').click());
  await pg.evaluate(async()=>{ await natRemove(); });
  ok('remove download deletes the model', await pg.evaluate(async()=>{ const root=await navigator.storage.getDirectory(); const n=[]; for await (const [k] of root.entries()) n.push(k); return !n.includes('supertonic-w8') && !(await pipDownloaded('st-M2')); }));
  ok('no page errors', !errs.length, errs);
  await b.close();
})();
